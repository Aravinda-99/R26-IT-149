/**
 * /api/errors/explain responses for one attempt, fetched once per (question, option) and
 * shared by the review panel and the Error Feedback page (stats + game plan).
 * Besides the explanation, a response carries the C2 label (from quizLab.js's analysis when
 * it has finished, else computed by the backend) and the final, possibly LLM-verified label.
 */
export function createExplanationStore(studentId, c2ByQuestion) {
    const responses = new Map(); // `${question_id}::${option}` -> response | Promise
    const keyOf = (item) => `${item.question_id}::${item.chosenOption}`;
    const payloadFor = (item) => {
        const c2 = c2ByQuestion[item.question_id];
        const payload = {
            student_id: studentId,
            question_id: item.question_id,
            chosen_option: item.chosenOption,
            code: item.code || "",
            is_correct: !!item.isCorrect,
        };
        if (c2 && !item.isCorrect) {
            payload.reason_group = c2.reason_group;
            payload.prediction_confidence = c2.prediction_confidence;
            payload.error_pattern_score = c2.error_pattern_score;
        }
        return payload;
    };
    return {
        peek(item) {
            const v = responses.get(keyOf(item));
            return v && !(v instanceof Promise) ? v : null;
        },
        get(item) {
            const key = keyOf(item);
            if (responses.has(key)) return Promise.resolve(responses.get(key));
            const p = ErrorAPI.explain(payloadFor(item)).then(res => {
                // The backend returns a template explanation whenever the LLM fails, so any
                // response carrying an explanation is used.
                if (res && res.explanation) responses.set(key, res);
                else responses.delete(key);
                return res;
            }).catch(err => {
                responses.delete(key);
                throw err;
            });
            responses.set(key, p);
            return p;
        },
        // Regenerate THIS answer's explanation now (the backend skips its cache). The result is
        // returned, never stored here: the page-wide label and stats stay on the first response.
        live(item) {
            return ErrorAPI.explain({ ...payloadFor(item), mode: "live" });
        },
    };
}


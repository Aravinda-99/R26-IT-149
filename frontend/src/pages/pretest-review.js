const fmtDate = (iso) => {
    const d = iso ? new Date(iso) : null;
    return d && !Number.isNaN(d.getTime()) ? d.toLocaleDateString([], { year: "numeric", month: "short", day: "numeric" }) : null;
};

// Short, student-readable reason why the live AI did not answer (the raw error stays in the tooltip).
const fallbackReason = (err) => (/rate limit|429|quota|paused|circuit/i.test(err) ? "AI quota reached"
    : /timed out|timeout/i.test(err) ? "AI took too long"
    : /not configured|switched off/i.test(err) ? "AI not configured"
    : "AI unavailable");

/** Where an explanation came from, from the /explain response: [css modifier, icon, label, tooltip]. */
function explanationSource(res) {
    if (res?.source === "cache") {
        const by = res.model ? ` by ${res.model}` : "";
        const on = fmtDate(res.generated_at) ? ` on ${fmtDate(res.generated_at)}` : "";
        return ["cache", "fa-box-archive", `Cached (generated${by}${on})`, "Saved earlier; not generated for this request"];
    }
    if (res?.source === "llm") {
        return ["llm", "fa-bolt", `Live now (${res.model || "LLM"})`, "Generated by the LLM for this request"];
    }
    if (res?.llm_error) {
        return ["warn", "fa-triangle-exclamation", `Template fallback — ${fallbackReason(res.llm_error)}`, res.llm_error];
    }
    return ["template", "fa-file-lines", "Template fallback", "Built from the reason-group template (no LLM)"];
}


export const friendlyReason = (rg) => (rg ? REASON_INFO[rg]?.[0] || rg.replace(/_/g, " ").toLowerCase() : null);
export const reasonMeaning = (rg) => (rg ? REASON_INFO[rg]?.[1] || "" : "");

// The single definition of a wrong answer (❌ in the list) — the Error Feedback stats
// and chart count with this too, so the numbers always agree with the list.
export const isWrongAnswer = (item) => item.answered && !item.isCorrect;

const pct = (v) => (typeof v === "number" ? `${Math.round(v * 100)}%` : null);

/**
 * "AI Error Detector" card — shared by the Pre-Test Review panel and the Java Sandbox's
 * "Analyze with AI". Shows ONE mistake type: the LLM-verified label when Model 3 was unsure
 * and the LLM disagreed (llmFinal), else Model 3's label.
 */
export function aiDetectorCardHtml({ isCorrect = false, topic = null, model3 = null, conf = null, llmFinal = null,
    version = null, loading = false, emptyMessage = "No AI diagnosis for this question (there is no code to analyse)." }) {
    if (isCorrect) {
        return `<div class="pr-detector pr-detector--ok" style="--c:var(--success);">
                <i class="fa-solid fa-circle-check" aria-hidden="true"></i> Correct ✓ — confirmed by answer key
            </div>`;
    }
    const badge = `<span class="pr-detector-badge"><i class="fa-solid fa-robot" aria-hidden="true"></i> AI Error Detector</span>`;
    const shown = llmFinal || model3;
    if (loading || !shown) {
        return `<div class="pr-detector" style="--c:var(--border-color);">
                <div class="pr-detector-head">${badge}</div>
                <div class="pr-detector-meaning" style="margin:0;">${escapeHtml(loading ? "Analysing your answer…" : emptyMessage)}</div>
            </div>`;
    }
    const noError = shown === "CORRECT_NO_ERROR";
    const mistakeConcept = conceptOfReason(shown);
    const color = noError ? "var(--success)" : conceptTheme(mistakeConcept || topic).color;
    const chips = [
        topic ? conceptChip(topic, "Question topic") : "",
        noError ? "" : conceptChip(mistakeConcept, "Mistake type", friendlyReason(shown)),
    ].join("");

    let meter = "";
    if (!llmFinal && typeof conf === "number") {
        // Same bands as the backend's High / Medium / Low confidence levels.
        const [level, mColor, icon] = conf >= 0.8 ? ["High", "var(--success)", "fa-circle-check"]
            : conf >= 0.5 ? ["Medium", "var(--warning)", "fa-circle-half-stroke"]
            : ["Low", "var(--danger)", "fa-circle-exclamation"];
        meter = `<div class="pr-meter" role="meter" aria-valuemin="0" aria-valuemax="100" aria-valuenow="${Math.round(conf * 100)}" aria-label="Confidence">
                <div class="pr-meter-fill" style="width:${pct(conf)};background:${mColor};"></div>
            </div>
            <div class="pr-meter-label"><i class="fa-solid ${icon}" style="color:${mColor};" aria-hidden="true"></i>${pct(conf)} · ${level} confidence</div>`;
    }
    const caption = llmFinal
        ? `Model 3 was unsure${pct(conf) ? ` (${pct(conf)})` : ""}, so our AI tutor (LLM) checked the code and chose this mistake type.`
        : `Detected by our AI model (Model 3)${version ? ` · ${escapeHtml(version)}` : ""}`;
    return `<div class="pr-detector" style="--c:${color};">
            <div class="pr-detector-head">${badge}</div>
            ${chips ? `<div class="pr-detector-chips">${chips}</div>` : ""}
            <div class="pr-detector-title">${escapeHtml(friendlyReason(shown))}</div>
            <div class="pr-detector-meaning">${escapeHtml(reasonMeaning(shown))}</div>
            ${topic && !noError ? `<div class="pr-caption" style="margin-top:0.3rem;"><i class="fa-solid fa-circle-info" aria-hidden="true"></i> The mistake type can be different from the question topic.</div>` : ""}
            ${meter}
            <div class="pr-caption">${caption}</div>
        </div>`;
}

